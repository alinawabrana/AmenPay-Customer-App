  String t(String key) {
    final lang = _localizedValues[locale.languageCode];
    if (lang != null && lang.containsKey(key)) return lang[key]!;
    final en = _localizedValues['en'];
    if (en != null && en.containsKey(key)) return en[key]!;
    return key;
  }

  String tf(String key, Map<String, String> params) {
    var value = t(key);
    params.forEach((k, v) {
      value = value.replaceAll('{$k}', v);
    });
    return value;
  }
